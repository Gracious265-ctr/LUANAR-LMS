"""Draft-application creation shared by the leave form and Leave Plans (Unit 04).

Both the "New Leave Application" form and a Leave Plan's **Apply Now** must
produce the *same* draft: status DRAFT, employee set, working days backfilled
from the same calendar. This is that single path, so the two entry points can
never drift.
"""

from __future__ import annotations

from datetime import date

from django.db import transaction

from leave.models import LeaveApplication, LeaveType
from leave.services.working_days import calculate_working_days


@transaction.atomic
def create_draft_application(
    *,
    employee,
    leave_type: LeaveType | int,
    start_date: date,
    end_date: date,
    reason: str = "",
    source_plan=None,
) -> LeaveApplication:
    """Create a leave application in DRAFT and return it.

    ``source_plan`` is the originating :class:`plans.LeavePlan` when the draft
    was generated by a plan, and ``None`` when the employee filed it by hand. It
    is bookkeeping only: it never affects validation, balances or approval.

    The draft is *not* submitted, so it reserves no balance, has no reference
    number and is invisible to approvers. Submission is a separate, later step.
    """
    application = LeaveApplication.objects.create(
        employee=employee,
        leave_type_id=leave_type.pk if isinstance(leave_type, LeaveType) else leave_type,
        start_date=start_date,
        end_date=end_date,
        reason=reason or "",
        status=LeaveApplication.Status.DRAFT,
        source_plan=source_plan,
    )
    # Working days are computed from the leave calendar once, then frozen.
    # Submission recomputes authoritatively; computing here only gives the
    # employee a realistic number while they are still editing the draft.
    application.calculated_days = calculate_working_days(start_date, end_date)
    application.save(update_fields=["calculated_days"])
    return application
